// Generates src/crypto/common-passwords.ts from the shared vectors (the list is
// the Go client's embedded list, copied verbatim). Run: node scripts/gen-common-passwords.mjs
// A test checks that the committed module equals the array in the vector file.
import { readFileSync, writeFileSync } from 'node:fs';
const v = JSON.parse(readFileSync(new URL('../../testvectors/crypto-v1.json', import.meta.url), 'utf8'));
const list = v.password_policy_common;
if (!Array.isArray(list) || list.length < 100) throw new Error('password_policy_common missing');
if (list.some((w) => typeof w !== 'string' || w === '' || w.includes(' '))) throw new Error('entries must be non-empty strings without spaces');
// One space-joined string: smaller in the bundle than an array of quoted strings.
const out = `// GENERATED by scripts/gen-common-passwords.mjs from testvectors/crypto-v1.json (password_policy_common). Do not edit.
export const COMMON_PASSWORDS: readonly string[] = ${JSON.stringify(list.join(' '))}.split(' ');
`;
writeFileSync(new URL('../src/crypto/common-passwords.ts', import.meta.url), out);
console.log(`wrote ${list.length} entries`);
