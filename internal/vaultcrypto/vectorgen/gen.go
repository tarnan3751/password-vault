func flip(b []byte, i int, mask byte) []byte {
	c := append([]byte(nil), b...)
	c[i] ^= mask
	return c
}

func genBox(f *File) {
	key := symKey("box")
	aad := []byte("fpv/v1/test|aad")
	multi := det("box/multi", 150) // > two 64-byte ChaCha blocks
	type pos struct {
		id, desc  string
		pt, aad   []byte
		nonceName string
	}
	for _, c := range []pos{
		{"box-basic", "short plaintext with AAD", []byte("hello vault"), aad, "n1"},
		{"box-empty-plaintext", "empty plaintext (box is exactly 41 bytes)", nil, aad, "n2"},
		{"box-empty-aad", "empty AAD", []byte("hello vault"), nil, "n3"},
		{"box-multi-block", "150-byte plaintext spanning several ChaCha20 blocks", multi, aad, "n4"},
		{"box-empty-both", "empty plaintext and empty AAD", nil, nil, "n5"},
	} {
		nonce := det("box/nonce/"+c.nonceName, 24)
		box := must(vc.SealWithNonce(key, nonce, c.pt, c.aad))
		f.Box = append(f.Box, BoxCase{ID: c.id, Description: c.desc, KeyHex: hx(key[:]), NonceHex: hx(nonce),
			PlaintextHex: hx(c.pt), AADHex: hx(c.aad), BoxHex: hx(box)})
	}
	base := must(vc.SealWithNonce(key, det("box/nonce/neg", 24), []byte("sensitive plaintext"), aad))
	neg := func(id, desc string, box []byte, aadUsed []byte, k *vc.SymmetricKey) {
		f.BoxNegative = append(f.BoxNegative, BoxNegative{ID: id, Description: desc, KeyHex: hx(k[:]), AADHex: hx(aadUsed), BoxHex: hx(box)})
	}
	neg("boxneg-flip-tag-bit", "last bit of the Poly1305 tag flipped", flip(base, len(base)-1, 0x01), aad, key)
	neg("boxneg-flip-ciphertext-bit", "first ciphertext bit flipped", flip(base, 25, 0x01), aad, key)
	neg("boxneg-flip-nonce-bit", "one nonce bit flipped", flip(base, 1, 0x80), aad, key)
	neg("boxneg-wrong-aad", "valid box, different AAD at open", base, []byte("fpv/v1/test|other"), key)
	neg("boxneg-missing-aad", "valid box, empty AAD at open although sealed with AAD", base, nil, key)
	neg("boxneg-wrong-key", "valid box, different key at open", base, aad, symKey("box-other"))
	neg("boxneg-version-0", "version byte 0x00", flip(base, 0, 0x01), aad, key)
	neg("boxneg-version-2", "version byte 0x02", flip(base, 0, 0x03), aad, key)
	neg("boxneg-truncated-40", "first 40 bytes only (one short of the 41-byte minimum)", base[:40], aad, key)
	neg("boxneg-truncated-tag", "last byte removed (length OK, tag short)", base[:len(base)-1], aad, key)
	neg("boxneg-extended", "one extra byte appended", append(append([]byte(nil), base...), 0), aad, key)
	neg("boxneg-empty", "empty input", nil, aad, key)
	neg("boxneg-version-only", "a single version byte", []byte{1}, aad, key)
}

func genWrap(f *File) {
	sender, recip, third := privKey("wrap/sender"), privKey("wrap/recipient"), privKey("wrap/third")
	vk := symKey("wrap/vk")
	ctx := vc.WrapContext{VaultID: detID("vault1"), KeyEpoch: 1, SenderID: detID("alice"), RecipientID: detID("bob")}

	mk := func(id, desc string, c vc.WrapContext, s, r *vc.PrivateKey, ephLabel string) WrapCase {
		eph := privKey("wrap/eph/" + ephLabel)
		nonce := det("wrap/nonce/"+ephLabel, 24)
		rp := pubOf(r)
		w := must(vc.WrapVaultKeyDeterministic(vk, c, s, &rp, eph, nonce))
		sp := pubOf(s)
		return WrapCase{ID: id, Description: desc,
			SenderPrivateHex: hx(s[:]), SenderPublicHex: sp.String(), SenderID: c.SenderID,
			RecipientPrivateHex: hx(r[:]), RecipientPublicHex: rp.String(), RecipientID: c.RecipientID,
			VaultID: c.VaultID, KeyEpoch: c.KeyEpoch, VaultKeyHex: hx(vk[:]),
			EphemeralPrivateHex: hx(eph[:]), EphemeralPublicHex: pubOf(eph).String(), NonceHex: hx(nonce),
			AADString: fmt.Sprintf("fpv/v1/vault-key|%s|%d|%s|%s", c.VaultID, c.KeyEpoch, c.SenderID, c.RecipientID),
			WrapHex:   hx(w)}
	}
	base := mk("wrap-basic", "alice wraps a vault key for bob, epoch 1", ctx, sender, recip, "a")
	f.VaultKeyWrap = append(f.VaultKeyWrap, base)
	c2 := ctx
	c2.KeyEpoch = 12
	f.VaultKeyWrap = append(f.VaultKeyWrap, mk("wrap-epoch-12", "two-digit key epoch (decimal, no padding in the AAD)", c2, sender, recip, "b"))
	c3 := ctx
	c3.RecipientID, c3.SenderID = ctx.SenderID, ctx.SenderID
	f.VaultKeyWrap = append(f.VaultKeyWrap, mk("wrap-self", "a user wraps a vault key for themselves (sender == recipient)", c3, sender, sender, "c"))
	c4 := ctx
	c4.KeyEpoch = 4294967295
	f.VaultKeyWrap = append(f.VaultKeyWrap, mk("wrap-epoch-max-uint32", "largest epoch, 2^32-1", c4, sender, recip, "d"))

	wb := unhex(base.WrapHex)
	neg := func(id, desc string, w []byte, mut func(n *WrapNegative)) {
		n := WrapNegative{ID: id, Description: desc, BaseCase: base.ID,
			RecipientPrivateHex: base.RecipientPrivateHex, SenderPublicHex: base.SenderPublicHex,
			SenderID: base.SenderID, RecipientID: base.RecipientID, VaultID: base.VaultID, KeyEpoch: base.KeyEpoch, WrapHex: hx(w)}
		if mut != nil {
			mut(&n)
		}
		f.VaultKeyWrapNegative = append(f.VaultKeyWrapNegative, n)
	}
	thirdPub := pubOf(third)
	neg("wrapneg-wrong-sender-public", "the directory returns a different public key for the sender", wb, func(n *WrapNegative) { n.SenderPublicHex = thirdPub.String() })
	neg("wrapneg-wrong-recipient-private", "unwrapped with someone else's private key", wb, func(n *WrapNegative) { n.RecipientPrivateHex = hx(third[:]) })
	neg("wrapneg-wrong-vault-id", "vault ID differs from the one wrapped", wb, func(n *WrapNegative) { n.VaultID = detID("vault2") })
	neg("wrapneg-wrong-epoch", "key epoch differs (2 instead of 1)", wb, func(n *WrapNegative) { n.KeyEpoch = 2 })
	neg("wrapneg-wrong-recipient-id", "recipient ID differs", wb, func(n *WrapNegative) { n.RecipientID = detID("carol") })
	neg("wrapneg-wrong-sender-id", "sender ID differs", wb, func(n *WrapNegative) { n.SenderID = detID("carol") })
	neg("wrapneg-swapped-ids", "sender and recipient IDs swapped", wb, func(n *WrapNegative) { n.SenderID, n.RecipientID = base.RecipientID, base.SenderID })
	for i, lo := range []struct{ name, pt string }{
		{"zero", strings.Repeat("00", 32)},
		{"one", "01" + strings.Repeat("00", 31)},
		{"order8", "e0eb7a7c3b41b8ae1656e3faf19fc46ada098deb9c32b1fd866205165f49b800"},
	} {
		w := append([]byte(nil), wb...)
		copy(w[1:33], unhex(lo.pt))
		neg(fmt.Sprintf("wrapneg-low-order-ephemeral-%d-%s", i+1, lo.name), "ephemeral public key is a low-order point ("+lo.name+"); the DH output is all zero and must be rejected", w, nil)
	}
	neg("wrapneg-low-order-sender-public", "sender public key supplied by the directory is all zero", wb, func(n *WrapNegative) { n.SenderPublicHex = strings.Repeat("00", 32) })
	neg("wrapneg-flip-ephemeral-bit", "one bit of the ephemeral public key flipped", flip(wb, 5, 0x01), nil)
	neg("wrapneg-flip-nonce-bit", "one nonce bit flipped", flip(wb, 40, 0x01), nil)
	neg("wrapneg-flip-ciphertext-bit", "one ciphertext bit flipped", flip(wb, 60, 0x01), nil)
	neg("wrapneg-flip-tag-bit", "last tag bit flipped", flip(wb, 104, 0x01), nil)
	neg("wrapneg-version-2", "version byte 0x02", flip(wb, 0, 0x03), nil)
	neg("wrapneg-truncated-104", "one byte short of 105", wb[:104], nil)
	neg("wrapneg-extended-106", "one byte too long", append(append([]byte(nil), wb...), 0), nil)
	neg("wrapneg-empty", "empty", nil, nil)
}
