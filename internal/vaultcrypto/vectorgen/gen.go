// det returns n deterministic bytes derived from label (SHA-256 in counter
// mode). These stand in for "random" values; they are written out in full in
// the vectors file, so consumers never need this function.
func det(label string, n int) []byte {
	var out []byte
	for ctr := uint32(0); len(out) < n; ctr++ {
		var c [4]byte
		binary.BigEndian.PutUint32(c[:], ctr)
		h := sha256.Sum256(append([]byte("fpv-vectors/"+label+"/"), c[:]...))
		out = append(out, h[:]...)
	}
	return out[:n]
}

func hx(b []byte) string { return hex.EncodeToString(b) }
func unhex(s string) []byte {
	b, err := hex.DecodeString(s)
	if err != nil {
		panic(err)
	}
	return b
}

func detID(label string) string { return hx(det("id/"+label, 16)) }

func symKey(label string) *vc.SymmetricKey {
	var k vc.SymmetricKey
	copy(k[:], det("key/"+label, 32))
	return &k
}

func privKey(label string) *vc.PrivateKey {
	var k vc.PrivateKey
	copy(k[:], det("priv/"+label, 32))
	return &k
}

func pubOf(p *vc.PrivateKey) vc.PublicKey {
	pub, err := vc.PublicFromPrivate(p)
	if err != nil {
		panic(err)
	}
	return pub
}

func must[T any](v T, err error) T {
	if err != nil {
		panic(err)
	}
	return v
}

func kdfOf(a AccountKDF) api.KDFParams {
	return api.KDFParams{Alg: "argon2id", Salt: unhex(a.SaltHex), Time: a.Time, MemoryKiB: a.MemoryKiB, Parallelism: a.Parallelism}
}

// Generate returns the exact bytes of testvectors/crypto-v1.json. It is
// deterministic: two runs yield identical output.
func Generate() (out []byte, err error) {
	defer func() {
		if r := recover(); r != nil {
			err = fmt.Errorf("vectorgen: %v", r)
		}
	}()
	f := &File{
		Suite:         "fpv/v1",
		SchemaVersion: 1,
		Description:   "Cross-language test vectors for docs/spec/crypto.md. Schema: testvectors/README.md. Generated by cmd/gen-vectors; do not edit by hand.",
		Encoding:      "Every raw binary value is a lowercase hex string in a field whose name ends in _hex. All other strings are literal UTF-8 text.",
	}
	genPublished(f)
	genKDF(f)
	genBox(f)
	genKeys(f)
	genWrap(f)
	genItems(f)
	genRosters(f)
	genDecoding(f)
	genReencrypt(f)
	genTrust(f)
	genPolicy(f)
	genAccounts(f)
	genBackups(f)

	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(f); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

